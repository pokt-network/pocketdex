// Session rosters: every session of every active (application, service) at each session start, with the suppliers the
// chain selected for it, and what each of them made of it once the session settled. The selection is computed by the
// indexer (src/mappings/pocket/sessionRosters.ts) from the indexed state, as poktroll's session hydrator does it
// (x/session/keeper/session_hydrator.go); it reproduces the chain from poktroll v0.1.33 on (mainnet 703,870), where the
// candidate sort stopped overflowing. Checked 2026-10-21 against the claims (no claim of a supplier outside its
// roster in 222 sessions from 703,870 on) and against get_session (.local/consumers/session-funnel/DESIGN.md).
//
// Two writes per session:
//   - at its start block (handleAddBlockReports): a session_rosters row and one session_suppliers row per member, state
//     active (0);
//   - at its settlement block: each member's final state, from the claims and the money tables of the block
//     (finalize_session_rosters), and the daily rollups the catalog reads.
// The states (session_suppliers.state):
//   0 active             the session is not settled yet
//   1 paid               its claim settled with settled_upokt > 0
//   2 settled_zero       its claim settled for 0
//   3 expired            its claim expired (no proof, or an invalid one)
//   4 discarded          its claim was discarded
//   5 slashed            its claim expired and the supplier was slashed for the missing proof
//   6 idle_others_worked it made no claim, and another member of the session did
//   7 idle_no_work       no member of the session made a claim (the application sent no work)
//   8 unresolved         it made a claim (MsgCreateClaim) that has no settlement, expiration or discard (should not
//                        happen; counted so that it shows)
// Ids are numbers of dictionaries (supplier_numbers from domainRewards.ts, application_numbers, service_numbers): a
// session_suppliers row is ~50 bytes, ~880k rows a day on mainnet.
export const SESSION_STATES = [
  "active",
  "paid",
  "settled_zero",
  "expired",
  "discarded",
  "slashed",
  "idle_others_worked",
  "idle_no_work",
  "unresolved",
];
const STATE_NAMES_SQL = `ARRAY[${SESSION_STATES.map((s) => `'${s}'`).join(", ")}]::text[]`;

